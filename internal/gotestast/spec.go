// NewTestSuiteSpecForTest creates a minimal TestSuiteSpec for use in unit tests.
func NewTestSuiteSpecForTest(name, pkgName string, isGenericAlias bool) *TestSuiteSpec {
	var underlyingTypeName string
	if isGenericAlias {
		underlyingTypeName = "GenericBase"
	}
	return &TestSuiteSpec{
		pkg:                &packages.Package{Name: pkgName},
		ts:                 &ast.TypeSpec{Name: ast.NewIdent(name)},
		th:                 &TestSuiteHarness{},
		underlyingTypeName: underlyingTypeName,
	}
}

type TestSuiteHarness struct {
	BeforeAll  *TestSuiteMethod
	BeforeEach *TestSuiteMethod
	AfterAll   *TestSuiteMethod
	AfterEach  *TestSuiteMethod
	TestCases  []*TestSuiteMethod
	// DeclaresTests survives the X_/F_ reduction of TestCases.
	DeclaresTests  bool
	Benchmarks     []*TestSuiteMethod
	Fuzzers        []*TestSuiteMethod
	Config         *types.Func // SuiteConfig() method, may be nil
	Guard          *types.Func // SuiteGuard() method, may be nil
	ConfigParallel bool
	// ConfigExclusive mirrors SuiteConfig.Exclusive, resolved statically so
	// the runner can schedule the suite outside the parallel bulk.
	ConfigExclusive bool
	// ConfigGroup mirrors SuiteConfig.ExclusiveGroup, resolved statically.
	ConfigGroup string
}

type TestSuiteMethod struct {
	n            ast.Node
	m            *types.Func
	sig          *types.Signature
	usesStdlibT  bool
	contextParam *types.Var // non-nil if method has a context parameter (2nd param)
	returnType   types.Type // non-nil if method returns a value (BeforeEach only)
}

// UsesStdlibT returns true if the method's parameter is *testing.T instead of *gotest.T.
func (m *TestSuiteMethod) UsesStdlibT() bool { return m.usesStdlibT }

func (m *TestSuiteMethod) HasContextParam() bool { return m.contextParam != nil }
func (m *TestSuiteMethod) HasReturn() bool       { return m.returnType != nil }

func (m *TestSuiteMethod) ContextTypeName(pkg *types.Package) string {
	if m.contextParam == nil {
		return ""
	}
	return types.TypeString(m.contextParam.Type(), qualifier(pkg))
}

func (m *TestSuiteMethod) ReturnTypeName(pkg *types.Package) string {
	if m.returnType == nil {
		return ""
	}
	return types.TypeString(m.returnType, qualifier(pkg))
}

func qualifier(pkg *types.Package) types.Qualifier {
	return func(other *types.Package) string {
		if other == pkg {
			return ""
		}
		return other.Name()
	}
}

func (m *TestSuiteMethod) Pos() token.Pos { return m.n.Pos() }

// NamePos is where the method's name is written.
func (m *TestSuiteMethod) NamePos() token.Pos { return m.m.Pos() }

// DeclaredAt is the method's declaration as base:line. The runtime names the
// full path under go test -fullpath (see callsite.Declared).
func (m *TestSuiteMethod) DeclaredAt(fset *token.FileSet) string {
	p := fset.Position(m.NamePos())
	if !p.IsValid() {
		return ""
	}
	return filepath.Base(p.Filename) + ":" + strconv.Itoa(p.Line)
}

func (m *TestSuiteMethod) IsFocused() bool  { return strings.HasPrefix(m.m.Name(), "F_") }
func (m *TestSuiteMethod) IsExcluded() bool { return strings.HasPrefix(m.m.Name(), "X_") }

// Identifier returns the test methods identifier.
//
// FOR RENDERING
func (m *TestSuiteMethod) Identifier() string {
	return m.m.Name()
}

// suiteConfigBodyErr describes the statically-parseable forms: the generator
// needs Parallel and Exclusive at generation time, so SuiteConfig bodies
// cannot be arbitrary Go.
const suiteConfigBodyErr = "SuiteConfig method body must return a gotest.SuiteConfig literal or preset call, optionally composed as `cfg := <literal|preset>` followed by plain `cfg.<Field> = <value>` assignments"

// staticSuiteConfig carries the SuiteConfig fields the generator and runner
// resolve statically. Everything else in SuiteConfig is runtime-only.
type staticSuiteConfig struct {
	Parallel  bool
	Exclusive bool
	Group     string
}

func parseSuiteConfigAST(pkg *packages.Package, funcDecl *ast.FuncDecl) (cfg staticSuiteConfig, err error) {
	body, err := ParseSuiteConfigBody(pkg.TypesInfo, funcDecl)
	if err != nil {
		return cfg, err
	}
	// Assignments follow the literal, so a later value wins.
	set := func(field string, value ast.Expr) {
		switch field {
		case "Parallel":
			cfg.Parallel, _ = boolLiteral(value)
		case "Exclusive":
			cfg.Exclusive, _ = boolLiteral(value)
		case "ExclusiveGroup":
			cfg.Group, _ = stringConstant(pkg.TypesInfo, value)
		}
	}
	for _, kv := range body.Fields {
		if key, ok := kv.Key.(*ast.Ident); ok {
			set(key.Name, kv.Value)
		}
	}
	for _, assign := range body.Assigns {
		set(assign.Lhs[0].(*ast.SelectorExpr).Sel.Name, assign.Rhs[0])
	}
	return cfg, nil
}

// isKnownSuitePreset accepts only the gotest-shipped presets as config bases:
// they are known to leave Parallel and Exclusive false, so static detection
// of both stays sound. The call must resolve to pkg/gotest — a same-named function or method
// from anywhere else could return Parallel: true and be silently mis-read.
func isKnownSuitePreset(call *ast.CallExpr, info *types.Info) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	if sel.Sel.Name != "DefaultSuiteConfig" && sel.Sel.Name != "IntegrationSuiteConfig" {
		return false
	}
	obj := info.ObjectOf(sel.Sel)
	if obj == nil || obj.Pkg() == nil {
		return false
	}
	return obj.Pkg().Path() == about.Repo+"/pkg/gotest"
}

func DetermineTestSuite(n ast.Node, pkg *packages.Package) (*TestSuiteSpec, token.Pos, error) {
	decl, ok := n.(*ast.GenDecl)
	if !ok || decl.Tok != token.TYPE {
		// we only care about type declarations
		return nil, -1, nil
	}

	// A suite is one declaration of its own: a block hides it from the
	// readers that look for its declaration, so it is refused there.
	if len(decl.Specs) != 1 {
		for _, spec := range decl.Specs {
			if ts, ok := spec.(*ast.TypeSpec); ok && IS_TEST_SUITE.MatchString(ts.Name.Name) {
				return nil, ts.Pos(), At(ts.Pos(), fmt.Errorf("suite %s is declared inside a type block; give it its own type declaration", ts.Name.Name))
			}
		}
		return nil, -1, nil // not a test suite
	}
	ts, ok := decl.Specs[0].(*ast.TypeSpec)
	if !ok {
		return nil, -1, nil // not a test suite
	}

	if !IS_TEST_SUITE.MatchString(ts.Name.Name) {
		return nil, -1, nil // not a test suite
	}

	if ts.TypeParams != nil && ts.TypeParams.NumFields() > 0 {
		return nil, -1, nil // generic definitions are not generation targets; their aliases are
	}

	var typ *types.Struct
	var underlyingTypeName string
	// an alias of an alias names the same suite
	rawType := types.Unalias(pkg.TypesInfo.TypeOf(ts.Type))
	if t, ok := rawType.(*types.Struct); ok {
		typ = t
	} else if named, ok := rawType.(*types.Named); ok {
		// a defined type has an empty method set: it would run nothing
		if !ts.Assign.IsValid() && IS_TEST_SUITE.MatchString(named.Obj().Name()) {
			return nil, ts.Pos(), At(ts.Pos(), fmt.Errorf("suite %s is defined over suite %s and carries none of its methods; declare an alias (= %s) or a struct of its own", ts.Name.Name, named.Obj().Name(), named.Obj().Name()))
		}
		if t, ok := named.Underlying().(*types.Struct); ok {
			typ = t
			underlyingTypeName = named.Obj().Name()
		}
	}
	if typ == nil {
		return nil, -1, nil
	}

	return &TestSuiteSpec{pkg: pkg, n: n, ts: ts, typ: typ, underlyingTypeName: underlyingTypeName, th: &TestSuiteHarness{}}, -1, nil
}

// detectParamB reports whether sig's sole parameter is *testing.B or *gotest.B.
// usesStdlibB is true for *testing.B; ok is false for any other signature shape.
func detectParamB(sig *types.Signature) (usesStdlibB bool, ok bool) {
	if sig.Params().Len() != 1 {
		return false, false
	}
	ptr, isPtr := sig.Params().At(0).Type().(*types.Pointer)
	if !isPtr {
		return false, false
	}
	named, isNamed := ptr.Elem().(*types.Named)
	if !isNamed {
		return false, false
	}
	obj := named.Obj()
	if obj.Name() != "B" {
		return false, false
	}
	pkg := obj.Pkg()
	if pkg == nil {
		return false, false
	}
	if pkg.Path() == "testing" {
		return true, true
	}
	return false, strings.HasSuffix(pkg.Path(), "/pkg/gotest")
}

// detectParamF reports whether sig's sole parameter is *gotest.F. Unlike
// detectParamB, *testing.F is NOT accepted here: fuzz lifecycle interposition
// (BeforeEach/AfterEach wired around every execution) requires gotest.F.
func detectParamF(sig *types.Signature) bool {
	if sig.Params().Len() != 1 {
		return false
	}
	pF := sig.Params().At(0).Type().String()
	return strings.HasPrefix(pF, "*"+about.Repo) && strings.HasSuffix(pF, "/gotest.F")
}

func DetermineTestSuiteHarness(n ast.Node, pkg *packages.Package, s *TestSuiteSpec) (token.Pos, error) {
	decl, ok := n.(*ast.FuncDecl)
	if !ok {
		// we only care about method declarations
		return -1, nil
	}
	if !decl.Name.IsExported() {
		return -1, nil
	}
	m, ok := pkg.TypesInfo.ObjectOf(decl.Name).(*types.Func)
	if !ok {
		return -1, nil
	}
	// methodID is a readable name, e.g. "MyTestSuite.BeforeAll" for improved debug output
	methodID := s.ts.Name.Name + "." + m.Name()

	if ok := IS_TEST_SUITE_METHOD.MatchString(m.Name()); !ok {
		return -1, nil
	}

	sig, ok := pkg.TypesInfo.TypeOf(decl.Name).(*types.Signature)
	if !ok {
		return -1, nil
	}
	recv := sig.Recv()
	if recv == nil {
		return -1, nil
	}
	{ // test for non-pointer suite receivers.
		// usage of value type receivers for test-suites is discouraged.
		namedRecvr, ok := types.Unalias(recv.Type()).(*types.Named)
		if ok {
			str := namedRecvr.Obj().Name()
			if IS_TEST_SUITE.MatchString(str) { // no receiver
				return decl.Name.Pos(), fmt.Errorf("signature of %q has unsupported value type receiver", decl.Name)
			}
			return -1, nil
		}
	}
	recvPtr, ok := types.Unalias(recv.Type()).(*types.Pointer)
	if !ok {
		return -1, nil
	}

	// a receiver may name the suite through an alias
	recvType, ok := types.Unalias(recvPtr.Elem()).(*types.Named)
	if !ok {
		return -1, nil
	}
	recvName := recvType.Obj().Name()
	if recvName != s.ts.Name.Name && (s.underlyingTypeName == "" || recvName != s.underlyingTypeName) {
		return decl.Name.Pos(), nil
	}

	if m.Name() == "SuiteConfig" {
		if sig.Params().Len() != 0 || sig.Results().Len() != 1 {
			return m.Pos(), fmt.Errorf("unsupported signature for %q: expected () gotest.SuiteConfig", methodID)
		}
		resType := sig.Results().At(0).Type().String()
		if !strings.HasSuffix(resType, "/gotest.SuiteConfig") {
			return m.Pos(), fmt.Errorf("unsupported return type for %q: expected gotest.SuiteConfig, got %s", methodID, resType)
		}
		s.th.Config = m
		staticCfg, err := parseSuiteConfigAST(pkg, decl)
		if err != nil {
			return m.Pos(), fmt.Errorf("%s.SuiteConfig: %w", s.ts.Name.Name, err)
		}
		s.th.ConfigParallel = staticCfg.Parallel
		s.th.ConfigExclusive = staticCfg.Exclusive
		s.th.ConfigGroup = staticCfg.Group
		return -1, nil
	}

	if m.Name() == "SuiteGuard" {
		if sig.Params().Len() != 0 || sig.Results().Len() != 1 {
			return m.Pos(), fmt.Errorf("unsupported signature for %q: expected () string", methodID)
		}
		resType := sig.Results().At(0).Type().String()
		if resType != "string" {
			return m.Pos(), fmt.Errorf("unsupported return type for %q: expected string, got %s", methodID, resType)
		}
		s.th.Guard = m
		return -1, nil
	}

	tm := &TestSuiteMethod{n: n, m: m, sig: sig}

	isTestCase := IS_TEST_CASE.MatchString(m.Name())
	isBenchmark := IS_BENCHMARK.MatchString(m.Name())
	isFuzz := IS_FUZZ.MatchString(m.Name())
	if (isTestCase || isBenchmark || isFuzz) && sig.Results().Len() > 0 {
		kind := "Test"
		switch {
		case isBenchmark:
			kind = protocol.PrefixBenchmark
		case isFuzz:
			kind = protocol.PrefixFuzz
		}
		return m.Pos(), fmt.Errorf("%s on %s returns a value; a %s method returns nothing", m.Name(), s.ts.Name.Name, kind)
	}
	switch {
	case IS_BEFORE_ALL.MatchString(m.Name()):
		s.th.BeforeAll = tm
	case IS_AFTER_ALL.MatchString(m.Name()):
		s.th.AfterAll = tm
	case IS_BEFORE_EACH.MatchString(m.Name()):
		s.th.BeforeEach = tm
	case IS_AFTER_EACH.MatchString(m.Name()):
		s.th.AfterEach = tm
	case isBenchmark:
		usesStdlibB, ok := detectParamB(sig)
		if !ok {
			return m.Pos(), fmt.Errorf("benchmark method %s must accept exactly one parameter of type *gotest.B or *testing.B", methodID)
		}
		tm.usesStdlibT = usesStdlibB
		s.th.Benchmarks = append(s.th.Benchmarks, tm)
		return -1, nil
	case isFuzz:
		if ok := detectParamF(sig); !ok {
			return m.Pos(), fmt.Errorf("fuzz method %s must accept exactly one parameter of type *gotest.F", methodID)
		}
		s.th.Fuzzers = append(s.th.Fuzzers, tm)
		return -1, nil
	case isTestCase:
		// pass-through: these will be handled further down the line
	default:
		return decl.Name.Pos(), fmt.Errorf("detected unhandled test suite method %q", methodID)
	}

	detectParamT := func(sig *types.Signature) (usesStdlib bool, err error) {
		pT := sig.Params().At(0).Type().String()
		switch {
		case pT == "*testing.T":
			return true, nil
		case strings.HasPrefix(pT, "*"+about.Repo) && strings.HasSuffix(pT, "/gotest.T"):
			return false, nil
		default:
			return false, fmt.Errorf("unsupported param type for signature of %q: must be *gotest.T or *testing.T", methodID)
		}
	}

	if !isTestCase {
		if IS_BEFORE_EACH.MatchString(m.Name()) {
			if sig.Params().Len() != 1 {
				return m.Pos(), fmt.Errorf("unsupported signature for %q: expected exactly 1 parameter", methodID)
			}
			if sig.Results().Len() > 1 {
				return m.Pos(), fmt.Errorf("unsupported signature for %q: expected 0 or 1 return values, got %d", methodID, sig.Results().Len())
			}
			usesStdlib, err := detectParamT(sig)
			if err != nil {
				return m.Pos(), err
			}
			tm.usesStdlibT = usesStdlib
			if sig.Results().Len() == 1 {
				tm.returnType = sig.Results().At(0).Type()
			}
			return -1, nil
		}

		if IS_AFTER_EACH.MatchString(m.Name()) {
			if sig.Params().Len() < 1 || sig.Params().Len() > 2 || sig.Results().Len() != 0 {
				return m.Pos(), fmt.Errorf("unsupported signature for %q: expected 1 or 2 parameters and no return values", methodID)
			}
			usesStdlib, err := detectParamT(sig)
			if err != nil {
				return m.Pos(), err
			}
			tm.usesStdlibT = usesStdlib
			if sig.Params().Len() == 2 {
				tm.contextParam = sig.Params().At(1)
			}
			return -1, nil
		}

		// BeforeAll, AfterAll — unchanged: exactly 1 param, 0 return values
		if sig.Params().Len() != 1 || sig.Results().Len() != 0 {
			return m.Pos(), fmt.Errorf("unsupported signature for %q", methodID)
		}
		usesStdlib, err := detectParamT(sig)
		if err != nil {
			return m.Pos(), err
		}
		tm.usesStdlibT = usesStdlib
		return -1, nil
	}

	if n := sig.Params().Len(); n >= 2 && sig.Params().At(n-1).Type().String() == "func()" {
		return m.Pos(), fmt.Errorf("test method %q takes a trailing done func(): async test methods are gone. Signal from the callback on a channel and wait for it in the method, asserting on the test goroutine:\n"+
			"\tdone := make(chan struct{})\n"+
			"\tgo func() { defer close(done); /* the work that called done() */ }()\n"+
			"\tselect {\n"+
			"\tcase <-done:\n"+
			"\tcase <-t.Context().Done():\n"+
			"\t\tgotest.Fail(t, \"never finished\")\n"+
			"\t}", methodID)
	}

	s.th.TestCases = append(s.th.TestCases, tm)
	s.th.DeclaresTests = true

	maxParams := 1

	// optional context parameter, from a returning BeforeEach
	if sig.Params().Len() >= 2 {
		tm.contextParam = sig.Params().At(1)
		maxParams += 1
	}

	if sig.Params().Len() != maxParams {
		return m.Pos(), fmt.Errorf("unsupported number of params for signature of %q", methodID)
	}

	usesStdlib, err := detectParamT(sig)
	if err != nil {
		return m.Pos(), err
	}
	tm.usesStdlibT = usesStdlib

	return -1, nil
}

// ValidateContextConsistency checks that all methods in the suite agree on whether
// they accept a context parameter, and that context types match BeforeEach's return type.
// The error carries the position of the method it is about (see PosOf).
func ValidateContextConsistency(ts *TestSuiteSpec) error {
	be := ts.th.BeforeEach
	ae := ts.th.AfterEach
	suiteName := ts.ts.Name.Name

	// An unexported suite with test cases is a silent false-green: go test only
	// runs exported Test functions, so its generated Test func would never
	// execute. Unexported case-less types (helpers) stay legal.
	if len(ts.th.TestCases) > 0 && !ts.ts.Name.IsExported() {
		return fmt.Errorf("test suite %q must be exported — go test never runs its generated Test function", suiteName)
	}

	// Bench Rule 1: benchmarks cannot coexist with a returning BeforeEach — a
	// returning-BeforeEach context type can't thread through *testing.B/*gotest.B.
	if len(ts.th.Benchmarks) > 0 && be != nil && be.HasReturn() {
		return At(be.NamePos(), fmt.Errorf("suite %s has benchmark methods but a returning BeforeEach — move benchmarks to a dedicated suite", suiteName))
	}

	// Bench Rule 2: bench lifecycles require *gotest.T hooks (not *testing.T).
	if len(ts.th.Benchmarks) > 0 {
		if ts.th.BeforeAll != nil && ts.th.BeforeAll.UsesStdlibT() {
			return At(ts.th.BeforeAll.NamePos(), fmt.Errorf("suite %s has benchmark methods but %s uses *testing.T — bench lifecycles require *gotest.T hooks", suiteName, "BeforeAll"))
		}
		if ts.th.AfterAll != nil && ts.th.AfterAll.UsesStdlibT() {
			return At(ts.th.AfterAll.NamePos(), fmt.Errorf("suite %s has benchmark methods but %s uses *testing.T — bench lifecycles require *gotest.T hooks", suiteName, "AfterAll"))
		}
		if be != nil && be.UsesStdlibT() {
			return At(be.NamePos(), fmt.Errorf("suite %s has benchmark methods but %s uses *testing.T — bench lifecycles require *gotest.T hooks", suiteName, "BeforeEach"))
		}
		if ae != nil && ae.UsesStdlibT() {
			return At(ae.NamePos(), fmt.Errorf("suite %s has benchmark methods but %s uses *testing.T — bench lifecycles require *gotest.T hooks", suiteName, "AfterEach"))
		}
	}

	// Fuzz Rule 1: fuzz methods cannot coexist with a returning BeforeEach — a
	// returning-BeforeEach context type can't thread through *gotest.F executions.
	if len(ts.th.Fuzzers) > 0 && be != nil && be.HasReturn() {
		return At(be.NamePos(), fmt.Errorf("suite %s has fuzz methods but a returning BeforeEach — move fuzz targets to a dedicated suite", suiteName))
	}

	// Fuzz Rule 2: fuzz lifecycles require *gotest.T hooks (not *testing.T).
	if len(ts.th.Fuzzers) > 0 {
		if ts.th.BeforeAll != nil && ts.th.BeforeAll.UsesStdlibT() {
			return At(ts.th.BeforeAll.NamePos(), fmt.Errorf("suite %s has fuzz methods but %s uses *testing.T — fuzz lifecycles require *gotest.T hooks", suiteName, "BeforeAll"))
		}
		if ts.th.AfterAll != nil && ts.th.AfterAll.UsesStdlibT() {
			return At(ts.th.AfterAll.NamePos(), fmt.Errorf("suite %s has fuzz methods but %s uses *testing.T — fuzz lifecycles require *gotest.T hooks", suiteName, "AfterAll"))
		}
		if be != nil && be.UsesStdlibT() {
			return At(be.NamePos(), fmt.Errorf("suite %s has fuzz methods but %s uses *testing.T — fuzz lifecycles require *gotest.T hooks", suiteName, "BeforeEach"))
		}
		if ae != nil && ae.UsesStdlibT() {
			return At(ae.NamePos(), fmt.Errorf("suite %s has fuzz methods but %s uses *testing.T — fuzz lifecycles require *gotest.T hooks", suiteName, "AfterEach"))
		}
	}

	// A benchmark wrapper hands every hook a T whose T() is nil; a fuzz
	// wrapper does so for BeforeAll and AfterAll only, its per-input hooks get
	// a real *testing.T.
	if err := hooksCallingT(ts); err != nil {
		return err
	}

	// Rule 1/7: Parallel requires returning BeforeEach (void BeforeEach forbidden)
	if ts.th.ConfigParallel && be != nil && !be.HasReturn() {
		return At(be.NamePos(), fmt.Errorf("%s: SuiteConfig has Parallel: true, but BeforeEach has no return value. Parallel methods require per-test isolation — move per-test fields to a context struct and return it from BeforeEach", suiteName))
	}

	if be == nil || !be.HasReturn() {
		// Void or absent BeforeEach — no methods should have context param
		for _, tc := range ts.th.TestCases {
			if tc.HasContextParam() {
				return At(tc.NamePos(), fmt.Errorf("%s.%s: has context parameter but BeforeEach does not return a context", suiteName, tc.Identifier()))
			}
		}
		// Rule 4: No orphan context AfterEach
		if ae != nil && ae.HasContextParam() {
			return At(ae.NamePos(), fmt.Errorf("%s.AfterEach: accepts a context parameter but BeforeEach does not return one", suiteName))
		}
		return nil
	}

	// Context type must be a pointer to a struct
	if _, ok := be.returnType.(*types.Pointer); !ok {
		return At(be.NamePos(), fmt.Errorf("%s.BeforeEach: return type %s must be a pointer", suiteName, be.returnType))
	}

	// Returning BeforeEach — ALL methods must have context param
	ctxType := be.returnType.String()

	for _, tc := range ts.th.TestCases {
		if !tc.HasContextParam() {
			return At(tc.NamePos(), fmt.Errorf("%s.%s: suite has a returning BeforeEach but this method does not accept the context parameter. All methods in a returning-BeforeEach suite must consistently include the context parameter", suiteName, tc.Identifier()))
		}
		// Rule 6: Type consistency
		if tc.contextParam.Type().String() != ctxType {
			return At(tc.NamePos(), fmt.Errorf("%s.%s: context parameter type %s does not match BeforeEach return type %s", suiteName, tc.Identifier(), tc.contextParam.Type(), be.returnType))
		}
	}

	// Rule 3: AfterEach matches BeforeEach
	if ae != nil {
		if !ae.HasContextParam() {
			return At(ae.NamePos(), fmt.Errorf("%s.AfterEach: suite has a returning BeforeEach but AfterEach does not accept the context. Add the context as the second parameter", suiteName))
		}
		if ae.contextParam.Type().String() != ctxType {
			return At(ae.NamePos(), fmt.Errorf("%s.AfterEach: context type %s does not match BeforeEach return type %s", suiteName, ae.contextParam.Type(), be.returnType))
		}
	}

	return nil
}

// hooksCallingT refuses the hooks that call t.T() where a wrapper of the
// suite hands them a nil one, naming them in source order at the first call.
func hooksCallingT(ts *TestSuiteSpec) error {
	bench, fuzz := len(ts.th.Benchmarks) > 0, len(ts.th.Fuzzers) > 0
	if !bench && !fuzz {
		return nil
	}
	type offender struct {
		name string
		pos  token.Pos
	}
	var found []offender
	perInput := false
	for _, h := range []struct {
		name     string
		m        *TestSuiteMethod
		perInput bool
	}{{"BeforeAll", ts.th.BeforeAll, false}, {"AfterAll", ts.th.AfterAll, false}, {"BeforeEach", ts.th.BeforeEach, true}, {"AfterEach", ts.th.AfterEach, true}} {
		// The fuzz wrapper runs the per-input hooks with a real *testing.T.
		if h.perInput && !bench {
			continue
		}
		if pos := h.m.callsT(ts.pkg); pos.IsValid() {
			found = append(found, offender{h.name, pos})
			perInput = perInput || h.perInput
		}
	}
	if len(found) == 0 {
		return nil
	}
	sort.Slice(found, func(i, j int) bool { return found[i].pos < found[j].pos })
	names := make([]string, len(found))
	for i, o := range found {
		names[i] = o.name
	}
	verb, list, hook := "calls", names[0], "hook"
	if len(names) > 1 {
		verb, list, hook = "call", strings.Join(names[:len(names)-1], ", ")+" and "+names[len(names)-1], "hooks"
	}
	// Name only the wrappers under which every named hook's T() is nil.
	kind := "fuzz"
	switch {
	case perInput || !fuzz:
		kind = "benchmark"
	case bench:
		kind = "fuzz and benchmark"
	}
	return At(found[0].pos, fmt.Errorf("suite %s has %s methods but %s %s t.T(), which is nil under them — check it for nil or move that work out of the %s", ts.ts.Name.Name, kind, list, verb, hook))
}

// callsT returns the position of the first T on the method's own *gotest.T
// parameter, or an alias of it, that is not proven non-nil where it is used;
// or token.NoPos. It reads the method's body, closures included, not the
// helpers it calls. A nil method has none.
func (m *TestSuiteMethod) callsT(pkg *packages.Package) token.Pos {
	decl, ok := m.node().(*ast.FuncDecl)
	if !ok || decl.Body == nil || m.sig.Params().Len() == 0 || m.usesStdlibT {
		return token.NoPos
	}
	w := &hookWalk{info: pkg.TypesInfo, parents: parentsOf(decl.Body), self: map[types.Object]bool{m.sig.Params().At(0): true}}
	w.followAliases(decl.Body)
	found := token.NoPos
	ast.Inspect(decl.Body, func(n ast.Node) bool {
		sel, ok := n.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != "T" || w.selfOf(sel.X) == nil || w.guarded(sel) {
			return true
		}
		if !found.IsValid() || sel.Sel.Pos() < found {
			found = sel.Sel.Pos()
		}
		return true
	})
	return found
}

// hookWalk reads one hook body: self holds its *gotest.T parameter and the
// local variables assigned from it.
type hookWalk struct {
	info    *types.Info
	parents map[ast.Node]ast.Node
	self    map[types.Object]bool
}

func parentsOf(root ast.Node) map[ast.Node]ast.Node {
	parents := map[ast.Node]ast.Node{}
	var stack []ast.Node
	ast.Inspect(root, func(n ast.Node) bool {
		if n == nil {
			stack = stack[:len(stack)-1]
			return false
		}
		if len(stack) > 0 {
			parents[n] = stack[len(stack)-1]
		}
		stack = append(stack, n)
		return true
	})
	return parents
}

// followAliases adds every variable assigned from self (tt := t, var tt = t,
// tt = t) until no more are found.
func (w *hookWalk) followAliases(body ast.Node) {
	for grown := true; grown; {
		grown = false
		add := func(id *ast.Ident, value ast.Expr) {
			if w.selfOf(value) == nil {
				return
			}
			obj := w.info.Defs[id]
			if obj == nil {
				obj = w.info.Uses[id]
			}
			if obj != nil && !w.self[obj] {
				w.self[obj], grown = true, true
			}
		}
		ast.Inspect(body, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.AssignStmt:
				if len(n.Lhs) == len(n.Rhs) {
					for i, l := range n.Lhs {
						if id, ok := l.(*ast.Ident); ok {
							add(id, n.Rhs[i])
						}
					}
				}
			case *ast.ValueSpec:
				if len(n.Names) == len(n.Values) {
					for i, id := range n.Names {
						add(id, n.Values[i])
					}
				}
			}
			return true
		})
	}
}

// selfOf returns the self variable e names, or nil.
func (w *hookWalk) selfOf(e ast.Expr) types.Object {
	if id, ok := ast.Unparen(e).(*ast.Ident); ok {
		if obj := w.info.Uses[id]; obj != nil && w.self[obj] {
			return obj
		}
	}
	return nil
}

// tCallOn returns the self variable e calls T() on, or nil.
func (w *hookWalk) tCallOn(e ast.Expr) types.Object {
	call, ok := ast.Unparen(e).(*ast.CallExpr)
	if !ok || len(call.Args) != 0 {
		return nil
	}
	sel, ok := ast.Unparen(call.Fun).(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "T" {
		return nil
	}
	return w.selfOf(sel.X)
}

// up returns n's parent, skipping parentheses.
func (w *hookWalk) up(n ast.Node) ast.Node {
	p := w.parents[n]
	for {
		if _, ok := p.(*ast.ParenExpr); !ok {
			return p
		}
		p = w.parents[p]
	}
}

// guarded reports whether the selector sel (x.T) is called and its result
// proven non-nil wherever it is used: compared with nil, under a nil check of
// the same call, or bound in an if-init and used only where it was checked.
func (w *hookWalk) guarded(sel *ast.SelectorExpr) bool {
	call, ok := w.up(sel).(*ast.CallExpr)
	if !ok || ast.Unparen(call.Fun) != sel {
		return false // a method value: T escapes unchecked
	}
	recv := w.selfOf(sel.X)
	if w.comparedWithNil(call) || w.checked(call, func(e ast.Expr) bool { return w.tCallOn(e) == recv }) {
		return true
	}
	return w.boundInIfInit(call)
}

func (w *hookWalk) isNil(e ast.Expr) bool {
	id, ok := ast.Unparen(e).(*ast.Ident)
	if !ok {
		return false
	}
	_, ok = w.info.Uses[id].(*types.Nil)
	return ok
}

// comparedWithNil reports whether e is an operand of == or != against nil.
func (w *hookWalk) comparedWithNil(e ast.Node) bool {
	b, ok := w.up(e).(*ast.BinaryExpr)
	if !ok || (b.Op != token.EQL && b.Op != token.NEQ) {
		return false
	}
	if ast.Unparen(b.X) == e {
		return w.isNil(b.Y)
	}
	return w.isNil(b.X)
}

// nilCheck reports whether cond is subject == nil (op EQL) or != nil (NEQ).
func (w *hookWalk) nilCheck(cond ast.Expr, op token.Token, subject func(ast.Expr) bool) bool {
	b, ok := ast.Unparen(cond).(*ast.BinaryExpr)
	if !ok || b.Op != op {
		return false
	}
	return (subject(b.X) && w.isNil(b.Y)) || (subject(b.Y) && w.isNil(b.X))
}

// nonNilIf reports whether cond being true proves subject non-nil.
func (w *hookWalk) nonNilIf(cond ast.Expr, subject func(ast.Expr) bool) bool {
	if b, ok := ast.Unparen(cond).(*ast.BinaryExpr); ok && b.Op == token.LAND {
		return w.nonNilIf(b.X, subject) || w.nonNilIf(b.Y, subject)
	}
	return w.nilCheck(cond, token.NEQ, subject)
}

// nonNilUnless reports whether cond being false proves subject non-nil.
func (w *hookWalk) nonNilUnless(cond ast.Expr, subject func(ast.Expr) bool) bool {
	if b, ok := ast.Unparen(cond).(*ast.BinaryExpr); ok && b.Op == token.LOR {
		return w.nonNilUnless(b.X, subject) || w.nonNilUnless(b.Y, subject)
	}
	return w.nilCheck(cond, token.EQL, subject)
}

// checked reports whether n sits where subject was proven non-nil: an if
// body or else branch, the right operand of && or ||, or after an
// `if subject == nil { …; return }` in the same block.
func (w *hookWalk) checked(n ast.Node, subject func(ast.Expr) bool) bool {
	for child, p := n, w.parents[n]; p != nil; child, p = p, w.parents[p] {
		switch p := p.(type) {
		case *ast.IfStmt:
			if (child == p.Body && w.nonNilIf(p.Cond, subject)) || (child == p.Else && w.nonNilUnless(p.Cond, subject)) {
				return true
			}
		case *ast.BinaryExpr:
			if child == p.Y && ((p.Op == token.LAND && w.nonNilIf(p.X, subject)) || (p.Op == token.LOR && w.nonNilUnless(p.X, subject))) {
				return true
			}
		case *ast.BlockStmt:
			for _, st := range p.List {
				if st == child {
					break
				}
				if is, ok := st.(*ast.IfStmt); ok && is.Else == nil && w.nonNilUnless(is.Cond, subject) && endsInReturn(is.Body) {
					return true
				}
			}
		}
	}
	return false
}

func endsInReturn(b *ast.BlockStmt) bool {
	if len(b.List) == 0 {
		return false
	}
	_, ok := b.List[len(b.List)-1].(*ast.ReturnStmt)
	return ok
}

// boundInIfInit reports whether call is bound in an if-init (if tt := t.T();
// …) and tt is used only in nil comparisons or where it was checked non-nil.
func (w *hookWalk) boundInIfInit(call *ast.CallExpr) bool {
	as, ok := w.up(call).(*ast.AssignStmt)
	if !ok || as.Tok != token.DEFINE || len(as.Lhs) != 1 || len(as.Rhs) != 1 {
		return false
	}
	is, ok := w.parents[as].(*ast.IfStmt)
	if !ok || is.Init != as {
		return false
	}
	id, _ := as.Lhs[0].(*ast.Ident)
	obj := w.info.Defs[id]
	if obj == nil {
		return false
	}
	isTT := func(e ast.Expr) bool {
		u, ok := ast.Unparen(e).(*ast.Ident)
		return ok && w.info.Uses[u] == obj
	}
	safe := true
	ast.Inspect(is, func(n ast.Node) bool {
		u, ok := n.(*ast.Ident)
		if !ok || w.info.Uses[u] != obj {
			return safe
		}
		safe = !w.mutable(u) && (w.comparedWithNil(u) || w.checked(u, isTT))
		return safe
	})
	return safe
}

// mutable reports whether id is assigned to or has its address taken, after
// which a nil check of it no longer holds.
func (w *hookWalk) mutable(id *ast.Ident) bool {
	switch p := w.up(id).(type) {
	case *ast.AssignStmt:
		for _, l := range p.Lhs {
			if ast.Unparen(l) == id {
				return true
			}
		}
	case *ast.UnaryExpr:
		return p.Op == token.AND
	}
	return false
}

// node returns the method's declaration, or nil for a nil method.
func (m *TestSuiteMethod) node() ast.Node {
	if m == nil {
		return nil
	}
	return m.n
}
