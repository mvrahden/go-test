package gotestruntime

import (
	"bytes"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
)

// goroutineID names the calling goroutine, as its traceback header does;
// zero when that header cannot be read.
func goroutineID() uint64 {
	var buf [64]byte
	header := buf[:runtime.Stack(buf[:], false)]
	header, ok := bytes.CutPrefix(header, []byte("goroutine "))
	if !ok {
		return 0
	}
	id, _, _ := bytes.Cut(header, []byte(" "))
	n, err := strconv.ParseUint(string(id), 10, 64)
	if err != nil {
		return 0
	}
	return n
}

// phaseFrame names the file:line where goroutine gid runs the phase the user
// wrote: the innermost frame below the harness that called it. Empty when
// the goroutine or such a frame cannot be found.
func phaseFrame(gid uint64) string {
	if gid == 0 {
		return ""
	}
	return userFrameBelowHarness(goroutineStack(gid))
}

// goroutineStack returns goroutine gid's traceback from a dump of all
// goroutines, nil when it is not in the dump.
func goroutineStack(gid uint64) []byte {
	buf := make([]byte, 64<<10)
	for {
		n := runtime.Stack(buf, true)
		if n < len(buf) || len(buf) >= 64<<20 {
			buf = buf[:n]
			break
		}
		buf = make([]byte, 2*len(buf))
	}
	header := []byte("goroutine " + strconv.FormatUint(gid, 10) + " [")
	for block := range bytes.SplitSeq(buf, []byte("\n\n")) {
		if bytes.HasPrefix(block, header) {
			return block
		}
	}
	return nil
}

// userFrameBelowHarness walks a traceback, innermost frame first, to the
// first harness frame and returns the location of the frame just inside it.
// Compiler wrappers (<autogenerated>) are skipped.
func userFrameBelowHarness(stack []byte) string {
	lines := strings.Split(string(stack), "\n")
	last := ""
	// lines[0] is the goroutine header; frames follow as function/location
	// pairs, the location indented with a tab.
	for i := 1; i+1 < len(lines); i += 2 {
		fn := lines[i]
		loc, ok := strings.CutPrefix(lines[i+1], "\t")
		if !ok {
			return "" // elided frames: the pairing is lost
		}
		file, _, _ := strings.Cut(loc, " +0x")
		if isHarnessFrame(fn, file) {
			return last
		}
		if strings.HasPrefix(file, "<autogenerated>") {
			continue
		}
		if path, line, ok := cutLine(file); ok {
			last = filepath.Base(path) + ":" + line
		}
	}
	return ""
}

// isHarnessFrame reports whether a frame belongs to the runtime package or
// to a generated suite harness.
func isHarnessFrame(fn, file string) bool {
	if strings.HasPrefix(fn, "github.com/mvrahden/go-test/pkg/gotestruntime.") || strings.Contains(fn, "ƒƒ_GOTEST") {
		return true
	}
	path, _, _ := cutLine(file)
	name := filepath.Base(path)
	return strings.HasSuffix(name, "gotest_psuite_test.go") || strings.HasSuffix(name, "gotest_pxsuite_test.go")
}

// cutLine splits "path:line" at its last colon, which a Windows drive
// letter cannot be.
func cutLine(loc string) (path, line string, ok bool) {
	i := strings.LastIndexByte(loc, ':')
	if i < 0 {
		return loc, "", false
	}
	return loc[:i], loc[i+1:], true
}
