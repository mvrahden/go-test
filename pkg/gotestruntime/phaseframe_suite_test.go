package gotestruntime_test

import (
	"fmt"
	"reflect"
	"runtime"

	"github.com/mvrahden/go-test/pkg/gotest"
	"github.com/mvrahden/go-test/pkg/gotestruntime"
)

// PhaseFrameTestSuite covers locating an overrunning phase in a traceback.
type PhaseFrameTestSuite struct{}

func (s *PhaseFrameTestSuite) SuiteConfig() gotest.SuiteConfig {
	cfg := gotest.DefaultSuiteConfig()
	cfg.Parallel = true
	return cfg
}

const hungMethod = `goroutine 7 [sleep]:
time.Sleep(0x59682f00)
	/usr/local/go/src/runtime/time.go:363 +0x165
example.com/pkg.(*CartTestSuite).TestHang(...)
	/src/pkg/cart_test.go:24
example.com/pkg.ƒƒ_GOTEST_exec(0x1?, 0x0?)
	/src/pkg/gotest_psuite_test.go:12 +0x19
github.com/mvrahden/go-test/pkg/gotestruntime.watchWhile(...)
	/mod/pkg/gotestruntime/harness.go:133 +0x1a2
testing.tRunner(0x1, 0x2)
	/usr/local/go/src/testing/testing.go:2193 +0xea
created by testing.(*T).Run in goroutine 6
	/usr/local/go/src/testing/testing.go:2258 +0x4d4`

func (s *PhaseFrameTestSuite) TestUserFrameBelowHarness(t *gotest.T) {
	t.It("names the user's frame the harness called, not the runtime frames inside it", func(it *gotest.T) {
		gotest.Equal(it, "cart_test.go:24", gotestruntime.ExportUserFrameBelowHarness([]byte(hungMethod)))
	})

	t.It("skips the compiler wrapper of a promoted hook", func(it *gotest.T) {
		gotest.Equal(it, "cart_test.go:31", gotestruntime.ExportUserFrameBelowHarness([]byte(`goroutine 7 [select (no cases)]:
example.com/pkg.(*CartTestSuite).BeforeAll(...)
	C:/src/pkg/cart_test.go:31
example.com/pkg.(*CartTestSuite).BeforeAll-fm(0x1)
	<autogenerated>:1 +0x2b
github.com/mvrahden/go-test/pkg/gotestruntime.RunSetup.func1()
	C:/mod/pkg/gotestruntime/harness.go:89 +0x1b`)))
	})

	t.It("names nothing when the harness itself is running, in the standard library", func(it *gotest.T) {
		pc := reflect.ValueOf(fmt.Fprintln).Pointer()
		file, line := runtime.FuncForPC(pc).FileLine(pc)
		gotest.Empty(it, gotestruntime.ExportUserFrameBelowHarness([]byte(fmt.Sprintf(`goroutine 7 [running]:
fmt.Fprintln({0x1, 0x2}, {0xc0, 0x1, 0x1})
	%s:%d +0x48
github.com/mvrahden/go-test/pkg/gotestruntime.reportAt({0x1, 0x2}, {0x0, 0x0}, {0xc0, 0x3c})
	/mod/pkg/gotestruntime/harness.go:226 +0x8a
github.com/mvrahden/go-test/pkg/gotestruntime.AwaitDoneAt(0xc0, {0x5, 0x12}, {0x0, 0x0}, 0xc0)
	/mod/pkg/gotestruntime/methods.go:110 +0x1a5`, file, line))))
	})

	t.It("names nothing when no harness frame is on the stack", func(it *gotest.T) {
		gotest.Empty(it, gotestruntime.ExportUserFrameBelowHarness([]byte(`goroutine 9 [running]:
main.main()
	/src/main.go:5 +0x1`)))
	})

	t.It("names nothing when frames were elided", func(it *gotest.T) {
		gotest.Empty(it, gotestruntime.ExportUserFrameBelowHarness([]byte(`goroutine 7 [running]:
example.com/pkg.deep(...)
	/src/pkg/deep.go:3
...additional frames elided...
example.com/pkg.ƒƒ_GOTEST_exec(0x1?, 0x0?)
	/src/pkg/gotest_psuite_test.go:12 +0x19`)))
	})
}
