package main_test

import (
	"os"
	"path/filepath"
	"time"

	. "github.com/mvrahden/go-test/cmd/gotest"

	"github.com/mvrahden/go-test/pkg/gotest"
)

// CleanTestSuite covers which files clean takes for generated ones.
type CleanTestSuite struct{}

func (s *CleanTestSuite) SuiteConfig() gotest.SuiteConfig {
	return gotest.SuiteConfig{Parallel: true, Timeout: 30 * time.Second}
}

func (s *CleanTestSuite) TestGeneratedFiles(t *gotest.T) {
	t.When("a package holds current and legacy generated files", func(w *gotest.T) {
		dir := w.TempDir()
		for _, name := range []string{"gotest_psuite_test.go", "gotest_pxsuite_test.go", "ƒƒ_psuite_test.go", "ƒƒ_pxsuite_test.go"} {
			gotest.NoError(w, os.WriteFile(filepath.Join(dir, name), []byte(generatedSource), 0o600))
		}
		gotest.NoError(w, os.WriteFile(filepath.Join(dir, "own_test.go"), []byte(generatedSource), 0o600))
		gotest.NoError(w, os.WriteFile(filepath.Join(dir, "foogotest_psuite_test.go"), []byte(generatedSource), 0o600))
		var names []string
		for _, path := range ExportGeneratedFiles(dir) {
			names = append(names, filepath.Base(path))
		}
		gotest.ElementsMatch(w, []string{"gotest_psuite_test.go", "gotest_pxsuite_test.go", "ƒƒ_psuite_test.go", "ƒƒ_pxsuite_test.go"}, names)
	})
}

func (s *CleanTestSuite) TestOwnFilesNamedLikeGenerated(t *gotest.T) {
	t.When("a file is named like a generated file but carries no generated-code comment", func(w *gotest.T) {
		dir := w.TempDir()
		path := filepath.Join(dir, "gotest_psuite_test.go")
		gotest.NoError(w, os.WriteFile(path, []byte("package p\n"), 0o600))
		gotest.False(w, ExportIsGenerated(path))
		gotest.NoError(w, os.WriteFile(path, []byte(generatedSource), 0o600))
		gotest.True(w, ExportIsGenerated(path))
	})
}

// generatedSource is a file as gotest generates it.
const generatedSource = "// Code generated by \"gotest (github.com/mvrahden/go-test)\"; DO NOT EDIT.\n\npackage p\n"
