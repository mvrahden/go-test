#!/usr/bin/env bash
# A harness an older gotest generated must keep compiling against this
# runtime: pkg/gotestruntime keeps every exported symbol and signature of
# the last release (a dropped call stays as a shim in deprecated.go).
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)
work="${TMPDIR:-/tmp}/gotest-runtimecompat-$(printf %s "$root" | cksum | cut -d' ' -f1)/api"

latest=$(git -C "$root" describe --tags --abbrev=0 --match 'v[0-9]*')
rm -rf "$work"
mkdir -p "$work/$latest"
git -C "$root" archive "$latest" | tar -x -C "$work/$latest"

export GOWORK=off
apidiff=(go run golang.org/x/exp/cmd/apidiff@latest)
(cd "$work/$latest" && "${apidiff[@]}" -w "$work/old.exp" ./pkg/gotestruntime)
report=$(cd "$root" && "${apidiff[@]}" -incompatible "$work/old.exp" ./pkg/gotestruntime)
if [ -n "$report" ]; then
  echo "$report" >&2
  echo "FAIL  pkg/gotestruntime breaks harnesses generated by $latest; keep the old symbol and add a new one" >&2
  exit 1
fi
echo "ok    pkg/gotestruntime keeps the API of $latest"
