#!/usr/bin/env bash
# A harness an older gotest generated must keep compiling against this
# runtime: pkg/gotestruntime keeps every exported symbol and signature of the
# last release (a dropped call stays as a shim in deprecated.go). pkg/gotest
# is the user API and prints every change; an incompatible one fails unless
# accepted-breaks.txt lists its apidiff line.
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)
work="${TMPDIR:-/tmp}/gotest-runtimecompat-$(printf %s "$root" | cksum | cut -d' ' -f1)/api"
accepted="$root/tests/runtimecompat/accepted-breaks.txt"

latest=$(git -C "$root" describe --tags --abbrev=0 --match 'v[0-9]*')
rm -rf "$work"
mkdir -p "$work/$latest"
git -C "$root" archive "$latest" | tar -x -C "$work/$latest"

export GOWORK=off
apidiff=(go run golang.org/x/exp/cmd/apidiff@latest)

# check PKG ACCEPTS: ACCEPTS=yes lets accepted-breaks.txt excuse a break.
check() {
  local pkg=$1 accepts=$2
  local exp="$work/${pkg//\//_}.exp"
  # errexit is off in a function called under ||: each step returns itself.
  (cd "$work/$latest" && "${apidiff[@]}" -w "$exp" "./$pkg") || return
  local breaks
  breaks=$(cd "$root" && "${apidiff[@]}" -incompatible "$exp" "./$pkg") || return

  if [ "$accepts" != yes ]; then
    if [ -n "$breaks" ]; then
      echo "$breaks" >&2
      echo "FAIL  $pkg breaks harnesses generated by $latest; keep the old symbol and add a new one" >&2
      return 1
    fi
    echo "ok    $pkg keeps the API of $latest"
    return
  fi

  local report
  report=$(cd "$root" && "${apidiff[@]}" "$exp" "./$pkg") || return
  if [ -n "$report" ]; then
    printf 'note  %s since %s:\n%s\n' "$pkg" "$latest" "$report"
    if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
      printf "%s since %s:\n\n\`\`\`\n%s\n\`\`\`\n" "$pkg" "$latest" "$report" >>"$GITHUB_STEP_SUMMARY"
    fi
  fi

  # Lines of the file that are neither comments nor empty.
  local listed
  listed=$(grep -v -e '^#' -e '^[[:space:]]*$' "$accepted" || true)
  local unaccepted stale
  unaccepted=$(awk 'NR == FNR { ok[$0] = 1; next } $0 != "" && !($0 in ok)' <(printf '%s\n' "$listed") <(printf '%s\n' "$breaks"))
  stale=$(awk 'NR == FNR { seen[$0] = 1; next } $0 != "" && !($0 in seen)' <(printf '%s\n' "$breaks") <(printf '%s\n' "$listed"))
  local line
  while IFS= read -r line; do
    [ -n "$line" ] && echo "note  tests/runtimecompat/accepted-breaks.txt lists a change apidiff no longer reports; remove: $line"
  done <<<"$stale"

  if [ -n "$unaccepted" ]; then
    echo "$unaccepted" >&2
    echo "FAIL  $pkg breaks code written against $latest; keep the old name, or list the line in tests/runtimecompat/accepted-breaks.txt with the release note that tells users what to change" >&2
    return 1
  fi
  if [ -n "$breaks" ]; then
    echo "ok    $pkg changes the API of $latest only where tests/runtimecompat/accepted-breaks.txt says so"
  else
    echo "ok    $pkg keeps the API of $latest"
  fi
}

status=0
check pkg/gotestruntime no || status=1
check pkg/gotest yes || status=1
exit $status
