#!/usr/bin/env bash
# Generated code must compile and run against gotestgen.MinRuntimeVersion:
# this tree's CLI runs a corpus requiring the floor release, and the corpus
# must reach every runtime symbol the templates call. A floor newer than the
# last release names the next one, which is this tree.
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)
repo=github.com/mvrahden/go-test
work="${TMPDIR:-/tmp}/gotest-runtimecompat-$(printf %s "$root" | cksum | cut -d' ' -f1)/floor"

floor=$(sed -n 's/^const MinRuntimeVersion = "\(v[^"]*\)"$/\1/p' "$root/internal/gotestgen/runtimeversion.go")
latest=$(git -C "$root" describe --tags --abbrev=0 --match 'v[0-9]*')
if git -C "$root" rev-parse -q --verify "refs/tags/$floor" >/dev/null; then
  target=$floor
elif [ "$(printf '%s\n%s\n' "$latest" "$floor" | sort -V | tail -n1)" = "$floor" ]; then
  target=
else
  echo "FAIL  MinRuntimeVersion $floor is no release and not after $latest" >&2
  exit 1
fi

rm -rf "$work"
mkdir -p "$work"
cp -R "$root/tests/runtimecompat/testdata/corpus" "$work/corpus"
(cd "$root" && go build -o "$work/gotest" ./cmd/gotest)
cd "$work/corpus"
export GOWORK=off
go mod init example.com/runtimecompat 2>/dev/null
if [ -n "$target" ]; then
  go get "$repo@$target"
else
  go mod edit -require="$repo@v0.0.0-00010101000000-000000000000" -replace="$repo=$root"
fi
go mod tidy

if ! "$work/gotest" --no-cache ./... >"$work/run.out" 2>&1; then
  cat "$work/run.out" >&2
  echo "FAIL  code generated by this tree does not run against runtime ${target:-$floor}; raise MinRuntimeVersion to the next release" >&2
  exit 1
fi

(cd "$root" && go build -o "$work/render" ./tests/runtimecompat/render)
"$work/render" ./... | grep -oE 'gotestruntime\.[A-Za-z_0-9]+' | sort -u >"$work/got"
grep -rhoE 'gotestruntime\.[A-Za-z_0-9]+' "$root/internal/gotestgen/static" | sort -u >"$work/want"
missing=$(comm -23 "$work/want" "$work/got")
if [ -n "$missing" ]; then
  echo "FAIL  the corpus in tests/runtimecompat/testdata/corpus generates no call to:" >&2
  echo "$missing" >&2
  exit 1
fi
if [ -n "$target" ]; then
  echo "ok    generated code runs against runtime $target"
else
  echo "ok    runtime floor $floor is the next release; generated code runs against this tree"
fi
